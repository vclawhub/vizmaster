const VECTOR_OPERATIONS = ['sum', 'difference', 'cross', 'scaled', 'projection'] as const;
type VectorOperation = (typeof VECTOR_OPERATIONS)[number];

/** Operations that combine two vectors; the rest act on the first one seen. */
const BINARY_OPERATIONS: readonly VectorOperation[] = ['sum', 'difference', 'cross', 'projection'];

interface VectorInput {
  x: number;
  y: number;
  z: number;
  label: string;
}

interface VectorSceneInput {
  vectors: VectorInput[];
  operations: VectorOperation[];
}

function renderVectorSceneFile(input: VectorSceneInput): { fileName: string; contents: string } {
  const binary = input.operations.filter((operation) => BINARY_OPERATIONS.includes(operation));
  if (binary.length > 0 && input.vectors.length < 2) {
    throw new Error(`${binary.join(', ')} need at least two vectors; received ${input.vectors.length}`);
  }
  if (input.operations.length === 0) throw new Error('request at least one operation, otherwise the scene has nothing to show');

  const [first, second] = input.vectors;
  const id = `vector-scene-${slugify(input.vectors.map((vector) => vector.label).join('-'), 'vectors')}`;
  const check = first && second ? first.x * second.x + first.y * second.y + first.z * second.z : undefined;

  const operationLines: string[] = [];
  const toggleLines: string[] = [];
  const stateLines: string[] = [];
  for (const [index, operation] of input.operations.entries()) {
    const call =
      operation === 'sum'
        ? `plotSum(new Vector(${first!.x}, ${first!.y}, ${first!.z}), new Vector(${second!.x}, ${second!.y}, ${second!.z}))`
        : operation === 'difference'
          ? `plotDifference(new Vector(${first!.x}, ${first!.y}, ${first!.z}), new Vector(${second!.x}, ${second!.y}, ${second!.z}))`
          : operation === 'cross'
            ? `plotCross(new Vector(${first!.x}, ${first!.y}, ${first!.z}), new Vector(${second!.x}, ${second!.y}, ${second!.z}))`
            : operation === 'scaled'
              ? `plotScaled(new Vector(${first!.x}, ${first!.y}, ${first!.z}), 2)`
              : `plotProjection(new Vector(${first!.x}, ${first!.y}, ${first!.z}), new Vector(${second!.x}, ${second!.y}, ${second!.z}))`;
    operationLines.push(`    scene.capture(${literal(operation)}, () => {`, `      scene.frame.${call};`, '    });');
    toggleLines.push(
      '        <label className="toggle">',
      `          <input type="checkbox" checked={enabled.${operation}} onChange={() => toggle(${literal(operation)})} />`,
      `          <span className="dot" style={{ background: ACCENT.green }} />${operationLabel(operation)}`,
      '        </label>',
    );
    stateLines.push(`  ${operation}: ${index === 0 ? 'true' : 'false'},`);
  }

  const pointLines = input.vectors.map(
    (vector, index) => `    scene.frame.addPoint(${vector.x}, ${vector.y}, ${vector.z}, ${literal(vector.label)}, VECTOR_COLORS[${index}], 0.07);`,
  );
  const baseLines = input.vectors.map(
    (vector, index) =>
      `      scene.frame.addVector({ x: ${vector.x}, y: ${vector.y}, z: ${vector.z} }, true, undefined, VECTOR_COLORS[${index}]);`,
  );
  const readoutLines = input.vectors.flatMap((vector) => [
    `          <dt>${vector.label}</dt>`,
    `          <dd>(${vector.x}, ${vector.y}, ${vector.z})</dd>`,
    `          <dt>|${vector.label}|</dt>`,
    `          <dd>${Math.hypot(vector.x, vector.y, vector.z).toFixed(3)}</dd>`,
  ]);

  const lines = [
    generatedHeader('renderVectorScene', 'Edit the tool, not this file.'),
    '',
    "import { useCallback, useEffect, useRef, useState } from 'react';",
    "import { Vector } from 'vectorplay';",
    '',
    "import { ACCENT, PALETTE } from '../lib/theme';",
    "import type { TutorialMeta } from '../lib/tutorial';",
    "import { mountVectorScene } from '../lib/vectorplay-scene';",
    "import type { VectorScene } from '../lib/vectorplay-scene';",
    '',
    'export const tutorial: TutorialMeta = {',
    `  id: ${literal(id)},`,
    `  title: ${literal(input.vectors.map((vector) => vector.label).join(', ') || 'Vector scene')},`,
    `  blurb: ${literal(`VectorPlay scene with ${input.operations.join(', ')} over ${input.vectors.length} vector(s).`)},`,
    "  kind: 'vectorplay',",
    "  generatedBy: 'renderVectorScene',",
    '};',
    '',
    'const VECTOR_COLORS = [ACCENT.purple, ACCENT.orange, \'#4ecdc4\', \'#ffe66d\', \'#a29bfe\', \'#ff7675\'] as const;',
    '',
    `const OPERATIONS = [${input.operations.map((operation) => literal(operation)).join(', ')}] as const;`,
    'type Operation = (typeof OPERATIONS)[number];',
    '',
    'export default function GeneratedVectorScene() {',
    '  const hostRef = useRef<HTMLDivElement | null>(null);',
    '  const sceneRef = useRef<VectorScene | null>(null);',
    '  const [enabled, setEnabled] = useState<Record<Operation, boolean>>({',
    ...stateLines,
    '  });',
    '',
    '  useEffect(() => {',
    '    const host = hostRef.current;',
    '    if (!host) return;',
    '',
    '    const scene = mountVectorScene(host, {',
    '      background: PALETTE.background,',
    '      gridLength: 16,',
    '      axisLength: 5,',
    '    });',
    '    sceneRef.current = scene;',
    '',
    '    // Labeled points at each vector tip.',
    ...pointLines,
    '',
    '    scene.capture(\'base\', () => {',
    ...baseLines,
    '    });',
    ...operationLines,
    '',
    '    return () => {',
    '      scene.dispose();',
    '      sceneRef.current = null;',
    '    };',
    '  }, []);',
    '',
    '  useEffect(() => {',
    '    const scene = sceneRef.current;',
    '    if (!scene) return;',
    '    const anyOperation = OPERATIONS.some((operation) => enabled[operation]);',
    "    scene.setVisible('base', !anyOperation);",
    '    for (const operation of OPERATIONS) scene.setVisible(operation, enabled[operation]);',
    '  }, [enabled]);',
    '',
    '  const toggle = useCallback((operation: Operation) => {',
    '    setEnabled((current) => ({ ...current, [operation]: !current[operation] }));',
    '  }, []);',
    '',
    '  return (',
    '    <div className="canvas-shell" ref={hostRef}>',
    '      <div className="overlay">',
    '        <h3>Vectors</h3>',
    '        <dl className="readout">',
    ...readoutLines,
    '        </dl>',
    check === undefined ? '' : '        <h3>First two vectors</h3>',
    check === undefined
      ? ''
      : `        <p className="control-note">dot product v₁ · v₂ = ${check}; the cross product is orthogonal to both inputs.</p>`,
    '        <h3>Operations</h3>',
    ...toggleLines,
    '      </div>',
    '      <p className="hint">drag to orbit · scroll to zoom · right-drag to pan</p>',
    '    </div>',
    '  );',
    '}',
    '',
  ];

  return { fileName: `${id}.tsx`, contents: lines.join('\n') };
}

function operationLabel(operation: VectorOperation): string {
  switch (operation) {
    case 'sum':
      return 'v₁ + v₂';
    case 'difference':
      return 'v₁ − v₂';
    case 'cross':
      return 'v₁ × v₂';
    case 'scaled':
      return '2v₁';
    case 'projection':
      return 'v₁ projected on v₂';
  }
}

