/**
 * OMP custom tools that generate new tutorials for this library.
 *
 * A custom tool module exports a factory that receives the host API (`pi`) and
 * returns tool definitions. Parameter schemas are built with `pi.zod` (the
 * Zod-compatible builder OMP injects), so inputs are validated before
 * `execute` runs, and the generated TypeScript is complete: each tool writes a
 * `.tsx` file into `src/tutorials/`, where the navigation shell discovers it
 * with `import.meta.glob` and typechecks it with the rest of the project.
 *
 * Nothing here evaluates model-provided strings: equations are parsed by a
 * whitelisted recursive-descent parser that emits a plain JS expression, so a
 * generated file never contains an `eval` and never contains a token the parser
 * did not understand.
 */

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';

import type { CustomTool, CustomToolFactory } from '@oh-my-pi/pi-coding-agent';

/* ------------------------------------------------------------------ *
 * Shared helpers
 * ------------------------------------------------------------------ */

const TUTORIAL_DIR = join('src', 'tutorials');

/** Header every generated file carries, so nobody hand-edits one by accident. */
function generatedHeader(tool: string, note: string): string {
  return [
    '/**',
    ` * Generated by the OMP custom tool \`${tool}\`. ${note}`,
    ' * Regenerate with the tool instead of editing: the generator owns this file.',
    ' */',
  ].join('\n');
}

function slugify(value: string, fallback: string): string {
  const slug = value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 48)
    .replace(/-+$/g, '');
  return slug.length > 0 ? slug : fallback;
}

/** A valid TypeScript string literal for arbitrary text. */
function literal(value: string): string {
  return JSON.stringify(value);
}

/**
 * Bridges zod-authored schemas into `CustomTool['parameters']`.
 *
 * OMP's docs (and the runtime bridge that feeds the shared validation pipeline)
 * accept the injected `pi.zod` builder, but the published `parameters` field is
 * declared as `TSchema = arktype Type | JSON-schema object`, and omptype's zod
 * schemas do not structurally match arktype's `Type` under that variance check.
 * One cast here keeps the documented zod authoring style; the schemas still
 * expose real `parse`/`safeParse`, which is what the runtime validates with.
 */
function zodParameters(schema: unknown): CustomTool['parameters'] {
  return schema as CustomTool['parameters'];
}

interface WrittenFile {
  relativePath: string;
  absolutePath: string;
  bytes: number;
}

async function writeTutorial(cwd: string, fileName: string, contents: string): Promise<WrittenFile> {
  const absolutePath = join(cwd, TUTORIAL_DIR, fileName);
  await mkdir(dirname(absolutePath), { recursive: true });
  const body = contents.endsWith('\n') ? contents : `${contents}\n`;
  await writeFile(absolutePath, body, 'utf8');
  return { relativePath: join(TUTORIAL_DIR, fileName), absolutePath, bytes: Buffer.byteLength(body, 'utf8') };
}

/** Unpacks an ascending two-element bound pair, rejecting anything else. */
function readBounds(values: number[], field: string): [number, number] {
  if (values.length !== 2) throw new Error(`${field} must hold exactly two bounds, received ${values.length}`);
  const low = values[0]!;
  const high = values[1]!;
  if (!(high > low)) throw new Error(`${field} must ascend, received [${low}, ${high}]`);
  return [low, high];
}

