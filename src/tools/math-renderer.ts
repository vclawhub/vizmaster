const MATH_FUNCTIONS: Record<string, string> = {
  sin: 'Math.sin',
  cos: 'Math.cos',
  tan: 'Math.tan',
  asin: 'Math.asin',
  acos: 'Math.acos',
  atan: 'Math.atan',
  sinh: 'Math.sinh',
  cosh: 'Math.cosh',
  tanh: 'Math.tanh',
  sqrt: 'Math.sqrt',
  cbrt: 'Math.cbrt',
  abs: 'Math.abs',
  exp: 'Math.exp',
  log: 'Math.log',
  ln: 'Math.log',
  pow: 'Math.pow',
  min: 'Math.min',
  max: 'Math.max',
  floor: 'Math.floor',
  ceil: 'Math.ceil',
  round: 'Math.round',
  sign: 'Math.sign',
  atan2: 'Math.atan2',
};

const MATH_CONSTANTS: Record<string, string> = {
  pi: 'Math.PI',
  'π': 'Math.PI',
  tau: '(2 * Math.PI)',
  e: 'Math.E',
};

type Token =
  | { kind: 'number'; text: string }
  | { kind: 'ident'; text: string }
  | { kind: 'operator'; text: '+' | '-' | '*' | '/' | '^' | ',' }
  | { kind: 'paren'; text: '(' | ')' };

const OPERATOR_SYMBOLS = new Set(['+', '-', '*', '/', '^', ',']);

/** Rewrites the notation a textbook uses into the notation the parser expects. */
function normalizeNotation(source: string): string {
  return source
    .replace(/^\s*(?:y|f\s*\(\s*x\s*\))\s*=\s*/, '')
    .replace(/\*\*/g, '^')
    .replace(/[−–—]/g, '-')
    .replace(/[×·∙]/g, '*')
    .replace(/÷/g, '/')
    .replace(/²/g, '^2')
    .replace(/³/g, '^3')
    .trim();
}

function tokenize(source: string): Token[] {
  const tokens: Token[] = [];
  let position = 0;
  while (position < source.length) {
    const character = source[position]!;
    if (/\s/.test(character)) {
      position += 1;
      continue;
    }
    if (/[0-9.]/.test(character)) {
      let text = '';
      while (position < source.length && /[0-9.]/.test(source[position]!)) {
        text += source[position];
        position += 1;
      }
      if (!/^(?:\d+(?:\.\d+)?|\.\d+)$/.test(text)) throw new Error(`"${text}" is not a number`);
      tokens.push({ kind: 'number', text });
      continue;
    }
    if (/[A-Za-zπ_]/.test(character)) {
      let text = '';
      while (position < source.length && /[A-Za-z0-9π_]/.test(source[position]!)) {
        text += source[position];
        position += 1;
      }
      tokens.push({ kind: 'ident', text });
      continue;
    }
    if (character === '(' || character === ')') {
      tokens.push({ kind: 'paren', text: character });
      position += 1;
      continue;
    }
    if (OPERATOR_SYMBOLS.has(character)) {
      tokens.push({ kind: 'operator', text: character as '+' | '-' | '*' | '/' | '^' | ',' });
      position += 1;
      continue;
    }
    throw new Error(`unsupported character "${character}"`);
  }
  return tokens;
}

/**
 * Compiles `2x^2 - 3x + 1` into `((2 * Math.pow(x, 2)) - (3 * x)) + 1`.
 *
 * A real parser rather than a chain of substitutions: precedence has to be
 * right (`-x^2` means `-(x²)`, powers bind tighter than unary minus and
 * associate to the right) and the output must never be able to smuggle in a
 * token the whitelist did not approve.
 */
class ExpressionCompiler {
  private position = 0;
  private usesVariable = false;

  constructor(
    private readonly tokens: Token[],
    private readonly variable: string,
  ) {}

  compile(): { expression: string; usesVariable: boolean } {
    const expression = this.readSum();
    const trailing = this.peek();
    if (trailing) throw new Error(`unexpected "${trailing.text}" after a complete expression`);
    return { expression, usesVariable: this.usesVariable };
  }

  private peek(): Token | undefined {
    return this.tokens[this.position];
  }

  private take(): Token {
    const token = this.tokens[this.position];
    if (!token) throw new Error('the expression ends before it is complete');
    this.position += 1;
    return token;
  }

  private readSum(): string {
    let left = this.readProduct();
    for (;;) {
      const token = this.peek();
      if (!token || token.kind !== 'operator' || (token.text !== '+' && token.text !== '-')) return left;
      this.take();
      left = `(${left} ${token.text} ${this.readProduct()})`;
    }
  }

  private readProduct(): string {
    let left = this.readUnary();
    for (;;) {
      const token = this.peek();
      if (token && token.kind === 'operator' && (token.text === '*' || token.text === '/')) {
        this.take();
        left = `(${left} ${token.text} ${this.readUnary()})`;
        continue;
      }
      // Implicit multiplication: "2x", "3(x + 1)", "(x - 1)(x + 2)".
      if (token && (token.kind === 'number' || token.kind === 'ident' || (token.kind === 'paren' && token.text === '('))) {
        left = `(${left} * ${this.readUnary()})`;
        continue;
      }
      return left;
    }
  }

  private readUnary(): string {
    const token = this.peek();
    if (token && token.kind === 'operator' && (token.text === '-' || token.text === '+')) {
      this.take();
      const operand = this.readUnary();
      return token.text === '-' ? `(-${operand})` : operand;
    }
    return this.readPower();
  }

  private readPower(): string {
    const base = this.readAtom();
    const token = this.peek();
    if (token && token.kind === 'operator' && token.text === '^') {
      this.take();
      return `Math.pow(${base}, ${this.readUnary()})`;
    }
    return base;
  }

  private readAtom(): string {
    const token = this.take();
    if (token.kind === 'number') return token.text;

    if (token.kind === 'paren') {
      if (token.text !== '(') throw new Error(`unexpected "${token.text}"`);
      const inner = this.readSum();
      const closing = this.take();
      if (closing.kind !== 'paren' || closing.text !== ')') throw new Error(`expected ")" but found "${closing.text}"`);
      return `(${inner})`;
    }

    if (token.kind === 'ident') {
      const fn = MATH_FUNCTIONS[token.text];
      if (fn) {
        const opening = this.take();
        if (opening.kind !== 'paren' || opening.text !== '(') {
          throw new Error(`expected "(" after ${token.text}`);
        }
        const args = [this.readSum()];
        for (;;) {
          const next = this.take();
          if (next.kind === 'paren' && next.text === ')') break;
          if (next.kind === 'operator' && next.text === ',') {
            args.push(this.readSum());
            continue;
          }
          throw new Error(`unexpected "${next.text}" inside ${token.text}(...)`);
        }
        return `${fn}(${args.join(', ')})`;
      }
      const constant = MATH_CONSTANTS[token.text];
      if (constant) return constant;
      if (token.text === this.variable) {
        this.usesVariable = true;
        return this.variable;
      }
      const allowed = ['x', ...Object.keys(MATH_FUNCTIONS), ...Object.keys(MATH_CONSTANTS)].join(', ');
      throw new Error(`unknown name "${token.text}"; allowed names are ${allowed}`);
    }

    throw new Error(`unexpected "${token.text}"`);
  }
}

function compileEquation(equation: string): { expression: string; usesVariable: boolean } {
  const normalized = normalizeNotation(equation);
  if (normalized.length === 0) throw new Error('the equation is empty');
  return new ExpressionCompiler(tokenize(normalized), 'x').compile();
}

/** A LaTeX rendering of a textbook-notation equation. */
function toLatex(equation: string): string {
  const normalized = normalizeNotation(equation)
    .replace(/\^(\d+)/g, '^{$1}')
    .replace(/\*/g, ' \\cdot ')
    .replace(/([0-9.])([a-zA-Z])/g, '$1$2');
  return `y = ${normalized}`;
}

/** Pixels per unit that keep a scene near 560 × 620 while staying square. */
function chooseScale(xSpan: number, ySpan: number): number {
  const byWidth = Math.floor(540 / xSpan);
  const byHeight = Math.floor(600 / ySpan);
  return Math.max(8, Math.min(48, byWidth, byHeight));
}

